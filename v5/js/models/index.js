// Сборка предмета по id из всех наборов и его место в комнате.
import { USSR, USSR_V4 } from "./ussr.js";
import { NEFORMAL } from "./neformal.js";
import { KAPITAL } from "./kapital.js";
import { PETS } from "./pets.js";
import { RADIATORS } from "./room.js";

const BUILD = { ...USSR, ...NEFORMAL, ...KAPITAL, ...PETS, ...RADIATORS };
const V4 = { ...USSR_V4 }; // «как было в v4» — для переделанных по фото
export const hasV4 = id => !!V4[id];

export function buildItem(id, T, v4) {
  const g = (v4 && V4[id] ? V4[id] : BUILD[id])(T);
  g.userData.id = id;
  return g;
}

